import { readFile, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { evidenceProfiles } from '../src/article-evidence-profiles.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputFile = path.join(root, 'src', 'article-evidence-translations.mjs');
const cacheFile = path.join(os.tmpdir(), 'bemama-article-evidence-translations-v1.json');
const targetLanguages = ['fa', 'ar', 'fr', 'tr', 'es', 'pt'];
const maxBatchCharacters = 2800;

let cache = {};
try {
  cache = JSON.parse(await readFile(cacheFile, 'utf8'));
} catch {
  cache = {};
}

const items = [];
for (const [profileId, profile] of Object.entries(evidenceProfiles)) {
  profile.guidance.forEach((text, index) => items.push({ key: `${profileId}.guidance.${index}`, text }));
  items.push({ key: `${profileId}.bemama`, text: profile.bemama });
  items.push({ key: `${profileId}.safety`, text: profile.safety });
}

for (const language of targetLanguages) {
  cache[language] ||= {};
  const missing = items.filter((item) => !cache[language][item.key]);
  const batches = createBatches(missing, maxBatchCharacters);
  console.log(`${language}: ${missing.length} strings in ${batches.length} batches`);

  for (let index = 0; index < batches.length; index += 1) {
    const batch = batches[index];
    const translated = await translateBatch(batch, language);
    Object.assign(cache[language], translated);
    await writeFile(cacheFile, `${JSON.stringify(cache, null, 2)}\n`, 'utf8');
    console.log(`${language}: completed batch ${index + 1}/${batches.length}`);
    await delay(140);
  }
}

const translations = {};
for (const language of targetLanguages) {
  translations[language] = {};
  for (const [profileId, profile] of Object.entries(evidenceProfiles)) {
    translations[language][profileId] = {
      guidance: profile.guidance.map((_, index) => required(language, `${profileId}.guidance.${index}`)),
      bemama: required(language, `${profileId}.bemama`),
      safety: required(language, `${profileId}.safety`)
    };
  }
}

const moduleSource = `// Generated by scripts/translate-article-evidence.mjs.\n` +
  `// Medical source URLs and official organization names remain in their original form.\n\n` +
  `export const evidenceTranslations = ${JSON.stringify(translations, null, 2)};\n`;

await writeFile(outputFile, moduleSource, 'utf8');
console.log(`Wrote ${outputFile}`);

function createBatches(sourceItems, limit) {
  const batches = [];
  let current = [];
  let currentLength = 0;
  for (const item of sourceItems) {
    const addition = item.text.length + 24;
    if (current.length && currentLength + addition > limit) {
      batches.push(current);
      current = [];
      currentLength = 0;
    }
    current.push(item);
    currentLength += addition;
  }
  if (current.length) batches.push(current);
  return batches;
}

async function translateBatch(batch, language) {
  const markers = batch.slice(0, -1).map((_, index) => `[[[${810000 + index}]]]`);
  const payload = batch.map((item, index) => `${item.text}${markers[index] ? `\n${markers[index]}\n` : ''}`).join('');
  const body = new URLSearchParams({ q: payload });
  let lastError;

  for (let attempt = 1; attempt <= 4; attempt += 1) {
    try {
      const response = await fetch(
        `https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=${language}&dt=t`,
        {
          method: 'POST',
          headers: { 'content-type': 'application/x-www-form-urlencoded;charset=UTF-8' },
          body
        }
      );
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const json = await response.json();
      const text = json[0].map((part) => part[0]).join('').trim();
      const values = splitTranslatedBatch(text, markers);
      if (values.length !== batch.length || values.some((value) => !value.trim())) {
        throw new Error(`Expected ${batch.length} translated strings, received ${values.length}`);
      }
      return Object.fromEntries(batch.map((item, index) => [item.key, values[index].trim()]));
    } catch (error) {
      lastError = error;
      await delay(attempt * 900);
    }
  }
  throw new Error(`Translation failed for ${language}: ${lastError?.message || lastError}`);
}

function splitTranslatedBatch(text, markers) {
  let values = [text];
  for (const marker of markers) {
    const next = [];
    for (const value of values) next.push(...value.split(marker));
    values = next;
  }
  return values.map((value) => value.trim());
}

function required(language, key) {
  const value = cache[language]?.[key];
  if (!value) throw new Error(`Missing ${language} translation: ${key}`);
  return value;
}

function delay(milliseconds) {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}
